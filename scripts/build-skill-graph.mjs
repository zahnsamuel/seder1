#!/usr/bin/env node
// Generates data/content-skill-graph.mjs: graph nodes for every skill assessed inside a
// content unit (tractate labs, Gemara arcs, Berakhot units, foundational literacy units,
// canon courses) that is not already covered by data/skill-graph.json (the hand-authored
// core) or data/non-gemara-skill-graph.mjs (the subject course chains).
//
//   node scripts/build-skill-graph.mjs        # rewrites data/content-skill-graph.mjs
//
// Design: the content itself already encodes fine-grained ordering (step order within a
// unit), so each unit becomes a prerequisite chain, and the chain's first skill anchors to
// a core-graph gate skill matched to the unit's curriculum role (labs gate on Mishnah
// orientation, arcs on Gemara context questions, conceptual units on conceptual reading).
// Cross-unit narrative ordering intentionally stays with the sequence recommenders; the
// graph's job is teachable-frontier eligibility, not a copy of the story line.
// test/skill-graph-coverage.test.mjs fails if content adds skills without regenerating.
import { writeFileSync, readFileSync } from 'node:fs';
import { loadUnits } from './audit-content.mjs';
import { nonGemaraSkillGraph } from '../data/non-gemara-skill-graph.mjs';

const core = JSON.parse(readFileSync('data/skill-graph.json', 'utf8')).skills;
const covered = new Set([...core, ...nonGemaraSkillGraph].map((s) => s.id));

// unit-id prefix -> { track, anchor } ; first match wins, top to bottom.
const CLASSIFY = [
  [/^lab:/, { track: 'gemara', anchor: 'mishnah-orientation' }],
  [/^course:/, { track: 'canon', anchor: 'identify-conceptual-claim' }],
  [/^berakhot-deep$/, { track: 'gemara', anchor: 'mishnah-orientation' }],
  [/^berakhot-/, { track: 'gemara', anchor: 'gemara-context-question' }],
  [/^(gemara-toolkit|gemara-middot|daf-literacy|grammar)$/, { track: 'language', anchor: 'source-signals' }],
  [/^aggadata-/, { track: 'gemara', anchor: 'source-signals' }],
  [/^shas-literacy/, { track: 'gemara', anchor: 'independent-sugya-reading' }],
  [/-arc$/, { track: 'gemara', anchor: 'gemara-context-question' }],
  [/^(halakha|chumash|tanakh)-/, { track: 'halakha', anchor: 'source-signals' }],
  [/^tefillah-/, { track: 'tefillah', anchor: 'source-signals' }],
  [/^(mussar|chassidus)-/, { track: 'mussar', anchor: 'identify-conceptual-claim' }],
  [/^(history|widerworld)-/, { track: 'history', anchor: 'identify-conceptual-claim' }],
  [/^(philosophy|thought)/, { track: 'thought', anchor: 'identify-conceptual-claim' }],
  [/./, { track: 'gemara', anchor: 'source-signals' }]
];

const routeFor = (unit) => {
  if (unit.kind === 'lab') return `lab.html?tractate=${unit.id.replace(/^lab:/, '')}`;
  if (unit.kind === 'course') return `canon-course.html?course=${unit.id.replace(/^course:/, '')}`;
  return `${unit.id}.html`;
};

// Readable unit label from its id ("lab:bava-metzia" -> "Bava Metzia lab"); completeTitle
// is a completion banner ("You can now..."), which reads badly inside a recommendation.
const labelFor = (unit) => {
  const base = unit.id.replace(/^(lab|course):/, '').replace(/-(arc|deep)$/, '').split('-')
    .map((word) => word[0].toUpperCase() + word.slice(1)).join(' ');
  return unit.kind === 'lab' ? `${base} lab` : unit.kind === 'course' ? `${base} course` : base;
};

const nodes = [];
const emitted = new Set();
for (const unit of loadUnits('.')) {
  const { track, anchor } = CLASSIFY.find(([re]) => re.test(unit.id))[1];
  const route = routeFor(unit);
  let previous = null; // last skill seen in this unit, covered or not, so chains stay intact
  unit.steps.forEach((s, i) => {
    if (!s.skill) return;
    const isLastSkillStep = !unit.steps.slice(i + 1).some((later) => later.skill);
    if (!covered.has(s.skill) && !emitted.has(s.skill)) {
      emitted.add(s.skill);
      nodes.push({
        id: s.skill,
        track,
        title: `${labelFor(unit)}: ${(s.title || s.short || s.skill).toString().slice(0, 60)}`,
        kind: s.typed ? 'translation-recall' : (s.independent || isLastSkillStep) ? 'transfer' : 'source-reading',
        prerequisites: [previous || anchor],
        languageDependencies: [],
        sourceForms: [s.ref || unit.id],
        evidence: 'Make this source-reading move inside its content unit.',
        masteryCriteria: s.typed ? 'Recall the translation anchor from memory.' : 'Use the move in the next source encounter.',
        reviewContexts: [s.ref || unit.id],
        route
      });
    }
    previous = s.skill;
  });
}

// Validate every prerequisite resolves in the merged graph before writing.
const all = new Set([...covered, ...emitted]);
const broken = nodes.flatMap((n) => n.prerequisites.filter((p) => !all.has(p)).map((p) => `${n.id} -> ${p}`));
if (broken.length) { console.error('Unresolvable prerequisites:\n' + broken.join('\n')); process.exit(1); }

const banner = `// GENERATED by scripts/build-skill-graph.mjs — do not hand-edit; regenerate after
// adding or renaming assessed skills in content units. Nodes for every content-assessed
// skill not already in data/skill-graph.json or data/non-gemara-skill-graph.mjs.
export const contentSkillGraph = [
`;
writeFileSync('data/content-skill-graph.mjs', banner + nodes.map((n) => JSON.stringify(n)).join(',\n') + '\n];\n');
console.log(`content-skill-graph.mjs written: ${nodes.length} nodes (core ${core.length} + non-Gemara ${nonGemaraSkillGraph.length} + content ${nodes.length} = ${core.length + nonGemaraSkillGraph.length + nodes.length} total)`);
